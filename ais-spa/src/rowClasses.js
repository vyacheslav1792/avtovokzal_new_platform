/** Класс строки в том виде, в котором его понимает фильтр ('' = без подсветки). */
export function rowClassKey(row) {
  return row && row._class ? String(row._class) : ''
}

/** Описание класса (для легенды и подсказок). */
export function rowClassInfo(key) {
  return ROW_CLASSES.find((c) => c.key === key) ?? null
}

