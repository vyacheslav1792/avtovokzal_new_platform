/**
 * Адрес страницы или новости из её заголовка.
 *
 * Адреса на сайте только латиницей (`/news/den-polya`): кириллица в URL
 * превращается в проценты, и скопированная ссылка становится нечитаемой.
 * Таблица транслитерации — та же, что в legacy-форке админки
 * (api/filesUploader.php), чтобы адреса выглядели привычно.
 */
const TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ь: '', ы: 'y', ъ: '', э: 'e', ю: 'yu', я: 'ya',
}

export function slugify(value, maxLength = 100) {
  return String(value || '')
    .toLowerCase()
    .replace(/[а-яё]/g, (c) => (c in TRANSLIT ? TRANSLIT[c] : c))
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, maxLength)
    // Обрезка по длине могла оставить дефис на конце.
    .replace(/-+$/g, '')
}
