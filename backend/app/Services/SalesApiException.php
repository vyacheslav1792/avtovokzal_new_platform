<?php

namespace App\Services;

class SalesApiException extends \RuntimeException
{
    /**
     * Отказы, которые НЕ являются сбоем: станция (или наша же проверка)
     * ответила «так нельзя», и сайт показывает покупателю обычное
     * сообщение.
     *
     * Их не нужно писать в журнал со стектрейсом: поисковые роботы ходят
     * по старым ссылкам расписания с прошедшими датами, и на проде это
     * давало 4601 запись ERROR за сутки — журнал backend разросся до 68 МБ,
     * а настоящие сбои в этой массе было не разглядеть (16.11.2026).
     */
    private const EXPECTED = [
        // Дата старше 48 часов: «Данные за этот период более недоступны».
        'date_out_of_range',
        'trip_not_found',
        'station_not_found',
        // Продажа или возврат по станции выключены в АИС — это решение
        // администратора, а не поломка.
        'station_sales_disabled',
        'station_refunds_disabled',
        /*
         * До базы станции нет связи (у Кром, например, нет интернета).
         * Такой отказ уже записан у sales-api — одной строкой на станцию
         * раз в пять минут; дублировать его здесь стектрейсом незачем, а
         * шло их по 2730 в сутки.
         */
        'station_unavailable',
        /*
         * «Заказ не оплачен»: покупатель вернулся со шлюза, не заплатив
         * (закрыл форму оплаты, банк отказал, передумал), а страница
         * результата всё равно спросила дооформление. Деньги не списаны,
         * бронь живёт до своего срока, заказ виден в АИС как ждущий
         * оплаты — сбоя здесь нет. На проде это давало 101 запись ERROR
         * со стектрейсом за сутки (16.11.2026).
         */
        'not_paid',
        /*
         * «Заказ имеет недопустимый статус»: открыта старая ссылка
         * `/payment/result` по заказу, который уже отменён или не
         * состоялся. Состояние заказа, а не сбой. Опасный случай
         * «деньги списаны, билетов нет» этой записью НЕ теряется: такой
         * заказ ловит `orders:cancel-abandoned`
         * (AbandonedPaymentService::candidates берёт и `failed` с
         * заполненным paid_at) и показывает карточка возврата в АИС
         * (состояние `unfinished_payment`).
         */
        'bad_order_status',
    ];

    public function __construct(
        string $message,
        public readonly string $errorCode = 'sales_api_error',
        /**
         * Код ответа API продаж. 4xx значит «неверный запрос» — то есть
         * виноваты входные данные, а не система; null — ответа не было
         * (это как раз сбой).
         */
        public readonly ?int $httpStatus = null,
        /**
         * Машиночитаемые подробности отказа API продаж (`details` в его
         * ответе). У отклонённого возврата там результат по КАЖДОМУ
         * бланку — по нему видно, какой именно бланк станция не приняла,
         * а не только «возврат не прошёл».
         *
         * @var array<string, mixed>
         */
        public readonly array $details = [],
    ) {
        parent::__construct($message);
    }

    /**
     * Отказы «такого нет» — ответ 404.
     *
     * Для страницы это важнее, чем кажется: по ссылкам на рейсы и тарифы
     * ходят поисковики, и 422 на несуществующий рейс для них значит
     * «страница есть, но запрос неверный» — она остаётся в выдаче и
     * обходится снова. 404 говорит «такого нет», а 503 (станция молчит) —
     * «вернись позже». До 21.11.2026 всё это отдавалось одним 422.
     */
    private const NOT_FOUND = [
        'trip_not_found',
        'route_not_found',
        'station_not_found',
        'stop_not_found',
        'boarding_point_not_found',
        'order_not_found',
    ];

    /**
     * Временная недоступность — ответ 503: станция не отвечает, сервис
     * продаж перезапускается, продажа выключена администратором. Запрос
     * верный, повторять его имеет смысл.
     */
    private const UNAVAILABLE = [
        'station_unavailable',
        'sales_api_unavailable',
        'station_sales_disabled',
        'station_refunds_disabled',
    ];

    /**
     * Код ответа сайта для этого отказа.
     *
     * Три состояния, которые нельзя путать: 404 — такого рейса, остановки
     * или станции не существует; 503 — временно недоступно, стоит
     * повторить; 422 — запрос некорректен (мусор в параметрах, строка,
     * которой нет в базе станции, нарушенные правила продажи).
     */
    public function responseStatus(): int
    {
        if (in_array($this->errorCode, self::NOT_FOUND, true)) {
            return 404;
        }

        if (in_array($this->errorCode, self::UNAVAILABLE, true)) {
            return 503;
        }

        // Ответа не было вовсе или API продаж ответил своей ошибкой —
        // это сбой на нашей стороне, а не неверный запрос.
        if ($this->httpStatus === null || $this->httpStatus >= 500) {
            return 503;
        }

        return 422;
    }

    /**
     * Конфликты продажи — всегда в журнал: они про деньги покупателя.
     * Проверяется раньше статуса ответа, потому что приходят они тоже
     * с 4xx.
     */
    private const ALWAYS_REPORT = [
        'already_sold',
        'sale_in_progress',
        'concurrent_sale',
        // Сервис продаж не ответил вовсе — это наш сбой, не чужой ввод.
        'sales_api_unavailable',
    ];

    /**
     * Штатный отказ, а не сбой — такие в журнал не пишем.
     *
     * Кроме перечисленных кодов сюда попадает ЛЮБОЙ отказ с кодом 4xx:
     * это ответ «неверный запрос», то есть виноваты пришедшие данные.
     * Боты и люди присылают что угодно — от этого журнал ошибок расти не
     * должен, иначе в нём не видно настоящих сбоев (на проде из 8023
     * записей ERROR за сутки такими были больше половины).
     *
     * Технические сбои остаются в журнале: 5xx у API продаж, отсутствие
     * ответа, нераспознанный формат — и конфликты продажи, см. выше.
     */
    public function isExpected(): bool
    {
        if (in_array($this->errorCode, self::ALWAYS_REPORT, true)) {
            return false;
        }

        if (in_array($this->errorCode, self::EXPECTED, true)) {
            return true;
        }

        return $this->httpStatus !== null && $this->httpStatus >= 400 && $this->httpStatus < 500;
    }
}
