<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Вход через VK ID
    |--------------------------------------------------------------------------
    |
    | В legacy входа через соцсети не было — это новая возможность кабинета.
    | Используем VK ID (OAuth 2.1 + PKCE) без JS-SDK: сайт уводит покупателя
    | на id.vk.ru/authorize, VK возвращает его на наш адрес с кодом, и код
    | на токен меняет backend. Никакого стороннего скрипта на страницах.
    |
    | Приложение заводится в кабинете разработчика VK (dev.vk.com). Оттуда:
    |   VK_CLIENT_ID     — идентификатор приложения (число),
    |   VK_CLIENT_SECRET — защищённый ключ; при PKCE обмен кода его НЕ
    |                      требует, поэтому он необязателен и оставлен на
    |                      случай серверных методов VK.
    |
    | Адрес возврата (`redirect_uri`) обязан совпадать байт в байт с тем,
    | что прописан в настройках приложения VK, и в запросе авторизации, и
    | в запросе токена — поэтому он собирается здесь один раз, из адреса
    | сайта (config/site.php), а не из текущего запроса.
    |
    | Без VK_CLIENT_ID вход через VK просто выключен: кнопки на страницах
    | входа и регистрации не показываются (как и с капчей на локальном
    | контуре — тестовых приложений VK не выдаёт).
    |
    */

    'client_id' => env('VK_CLIENT_ID'),
    'client_secret' => env('VK_CLIENT_SECRET'),

    // Пустой VK_CLIENT_ID (переменная есть, значения нет) — тоже «выключено».
    'enabled' => (bool) env('VK_ENABLED', trim((string) env('VK_CLIENT_ID')) !== ''),

    // Куда VK возвращает покупателя: маршрут сервера Nuxt, который положит
    // выданный токен в httpOnly cookie сессии.
    'redirect_uri' => (string) env(
        'VK_REDIRECT_URI',
        rtrim((string) env('FRONTEND_URL', 'http://127.0.0.1:3000'), '/').'/auth/vk/callback',
    ),

    /*
    | Запрашиваемые права. `vkid.personal_info` — имя и фото (без него VK не
    | отдаёт вообще ничего), `email` и `phone` — контакты, если покупатель их
    | разрешит. Оба необязательны: VK может не вернуть ни того, ни другого,
    | и кабинет обязан это пережить (e-mail тогда просто предлагаем ввести).
    */
    'scope' => env('VK_SCOPE', 'vkid.personal_info email phone'),

    // Хосты VK ID. id.vk.ru — основной, id.vk.com ведёт туда же.
    'authorize_url' => env('VK_AUTHORIZE_URL', 'https://id.vk.ru/authorize'),
    'token_url' => env('VK_TOKEN_URL', 'https://id.vk.ru/oauth2/auth'),
    'user_info_url' => env('VK_USER_INFO_URL', 'https://id.vk.ru/oauth2/user_info'),
    'logout_url' => env('VK_LOGOUT_URL', 'https://id.vk.ru/oauth2/logout'),

    // Секунды на ответ VK ID.
    'timeout' => (int) env('VK_TIMEOUT', 10),

    /*
    | Сколько минут живёт начатая авторизация. Между уходом на VK и возвратом
    | лежат code_verifier и адрес возврата — держим их в кэше по ключу state
    | (backend отвечает на запросы без сессии, класть их в сессию некуда).
    | Сам код VK живёт 10 минут — больше и не нужно.
    */
    'state_ttl_minutes' => (int) env('VK_STATE_TTL_MINUTES', 15),

];
