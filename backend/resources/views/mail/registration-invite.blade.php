# Спасибо за покупку!

Вы купили билет на сайте автовокзалов Орловской области. Чтобы билеты, история поездок
и возврат всегда были под рукой, заведите личный кабинет — это займёт минуту.

В кабинете вы сможете:

- видеть все покупки, сделанные на этот адрес: **{{ $email }}**;
- распечатать билет или скачать его в PDF;
- вернуть билет без ввода кода с билета;
- не заполнять при следующей покупке почту и телефон.

Чтобы завести кабинет, откройте сайт автовокзала, выберите «Личный кабинет» →
«Регистрация» и укажите **этот самый адрес**: мы пришлём на него код из 6 цифр,
и после его ввода все прошлые покупки окажутся в кабинете.

Если вы не покупали билет, просто не обращайте внимания на это письмо —
кабинет без вашего участия создан не будет.

Хорошей дороги!

