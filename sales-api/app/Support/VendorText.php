<?php

namespace App\Support;

use Closure;

/**
 * Правила проверки СТРОК, уходящих в вендорную базу BUSTER (название
 * остановки, ФИО пассажира, серия и номер документа, номера бланков) —
 * пара к {@see VendorCode}, который проверяет числовые коды.
 *
 * Зачем отдельное правило: базы станций живут в WIN1251, а соединение
 * открыто в UTF8 (`charset=UTF8` в DSN — так делал и legacy), то есть
 * параметры конвертирует сам Firebird. На символе, которого в WIN1251
 * нет, он отвечает «-802 Cannot transliterate character between
 * character sets», а на строке длиннее поля — «-303 String data, right
 * truncated». И то и другое — ответ 500 покупателю и девять килобайт
 * стектрейса в журнале на один мусорный запрос.
 *
 * Ловилось на проде 19.11.2026 в 19:15: обходчик (Baidu, IP из Китая)
 * открыл `/trips?awtcod=5706&from=…&to=…` с названиями остановок в
 * ДВОЙНОЙ кодировке UTF-8 — «Металлург дв» приехало как
 * `%C3%90%C2%9C%C3%90%C2%B5…`, то есть «ÐœÐµÑ‚Ð°Ð»Ð»ÑƒÑ€Ð³ Ð´Ð²», где
 * стоят `œ`, `‚`, `€` — в WIN1251 их нет. Один такой запрос дал две
 * записи ERROR: у sales-api (-802 из `fetchAll`) и у backend
 * («Server Error» от API продаж).
 *
 * Отказ здесь штатный (422, ошибка проверки в журнал не пишется) и по
 * смыслу верный: названия, непредставимого в WIN1251, в базе станции
 * быть не может — искать там нечего.
 *
 * Чего тут сознательно НЕТ: попытки «починить» двойную кодировку
 * обратным преобразованием. Какой именно кодировкой строку испортили по
 * дороге — догадка, а испортить ею настоящее название (его присылает
 * наш же сайт) куда дороже, чем отказать обходчику.
 */
final class VendorText
{
    /**
     * Название остановки — `TRACES.STATNAME`, WIN1251.
     *
     * **Ширина поля у станций РАЗНАЯ** (проверено по RDB$FIELDS на боевых
     * базах 19.11.2026): Орел, Мценск и Колпны — `varchar(50)`, Залегощь —
     * `varchar(20)`. Поэтому предел по самой узкой поставить нельзя: на
     * Орле есть настоящие остановки длиной 27 символов («Москва АВ
     * Красногвардейский» — по ней 635 покупок), и `max:20` отказал бы
     * живым покупателям.
     *
     * Строка шире поля даёт не «ничего не найдено», а ошибку Firebird
     * -303 «String data, right truncated» (проверено: 20 проходит, 40
     * падает). Закрыть это одной длиной нельзя — поэтому здесь отсекается
     * заведомо невозможное (шире самого широкого поля), а отказ станции по
     * фактической ширине превращает во внятный ответ
     * `BusterConnection::isBadParameterValue`.
     */
    public const MAX_STATION_NAME = 50;

    /**
     * Правила для строки, которая уйдёт в вендорную базу.
     *
     * @return array<int, mixed>
     */
    public static function rules(int $max, bool $required = true): array
    {
        return [$required ? 'required' : 'nullable', 'string', 'max:'.$max, self::charsetRule()];
    }

    /**
     * Только проверка кодировки — для полей, у которых длина и формат уже
     * заданы своими правилами (ФИО, документ, номер бланка).
     */
    public static function charsetRule(): Closure
    {
        return function (string $attribute, mixed $value, Closure $fail): void {
            if (is_string($value) && ! self::fits($value)) {
                $fail('Поле «:attribute» содержит символы, которых нет в базе станции.');
            }
        };
    }

    /**
     * Строка целиком представима в WIN1251 (кодировке баз станций)?
     *
     * Проверяем переводом туда и обратно: непредставимый символ
     * mbstring заменяет на «?», и обратный перевод с исходной строкой уже
     * не совпадает. Невалидный UTF-8 (байтовый мусор от ботов) отсекается
     * тем же способом. iconv для этого не годится: без `//IGNORE` он на
     * таком символе поднимает предупреждение, которое Laravel превращает
     * в исключение, — то есть лечение было бы той же болезнью.
     */
    public static function fits(string $value): bool
    {
        $win1251 = mb_convert_encoding($value, 'CP1251', 'UTF-8');

        return mb_convert_encoding($win1251, 'UTF-8', 'CP1251') === $value;
    }
}
